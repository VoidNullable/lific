#!/usr/bin/env bash
# Print the Homebrew formula for a published release.
#
# The formula installs the prebuilt release binaries, so it is generated from
# the release's own sha256sums.txt rather than from a local build: the hashes
# it pins are exactly the ones users download. The release workflow pushes the
# output to VoidNullable/homebrew-tap as Formula/lific.rb.
#
#   bash scripts/render-homebrew-formula.sh 2.11.1 sha256sums.txt > lific.rb
set -euo pipefail

version="${1:?usage: render-homebrew-formula.sh VERSION SHA256SUMS}"
sums="${2:?usage: render-homebrew-formula.sh VERSION SHA256SUMS}"
version="${version#v}"

if [[ ! $version =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]]; then
  echo "version '$version' is not MAJOR.MINOR.PATCH" >&2
  exit 1
fi
if [[ ! -r $sums ]]; then
  echo "cannot read checksum file '$sums'" >&2
  exit 1
fi

# sha256sum writes "<hash>  <name>", or "<hash> *<name>" in binary mode.
checksum() {
  local name="$1" hash
  hash="$(awk -v name="$name" '{ file = $2; sub(/^\*/, "", file) } file == name { print $1; exit }' "$sums")"
  if [[ ! $hash =~ ^[0-9a-f]{64}$ ]]; then
    echo "no sha256 for $name in $sums" >&2
    exit 1
  fi
  printf '%s\n' "$hash"
}

macos_arm="$(checksum lific-macos-aarch64)"
macos_intel="$(checksum lific-macos-x86_64)"
linux_arm="$(checksum lific-linux-aarch64)"
linux_intel="$(checksum lific-linux-x86_64)"
base="https://github.com/VoidNullable/lific/releases/download/v${version}"

cat <<EOF
# Generated by scripts/render-homebrew-formula.sh in VoidNullable/lific.
# The release workflow overwrites this file on every release; edit the script.
class Lific < Formula
  desc "Local-first issue tracker for AI agents, with an MCP server and web UI"
  homepage "https://lific.dev"
  version "${version}"
  license "Apache-2.0"

  on_macos do
    on_arm do
      url "${base}/lific-macos-aarch64"
      sha256 "${macos_arm}"
    end
    on_intel do
      url "${base}/lific-macos-x86_64"
      sha256 "${macos_intel}"
    end
  end

  on_linux do
    on_arm do
      url "${base}/lific-linux-aarch64"
      sha256 "${linux_arm}"
    end
    on_intel do
      url "${base}/lific-linux-x86_64"
      sha256 "${linux_intel}"
    end
  end

  def install
    bin.install Dir["lific-*"].fetch(0) => "lific"
    chmod 0755, bin/"lific"
    generate_completions_from_executable(bin/"lific", "completion")
  end

  def caveats
    return unless OS.linux?

    <<~EOS
      A background service set up by \`lific init\` runs this exact version.
      After \`brew upgrade lific\`, run \`lific service install\` (with the same
      --config, if you used one) so the service runs the new version.
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/lific --version")
  end
end
EOF
